CREATE TABLE USERS (
    USER_ID NUMBER NOT NULL,
    ROLE VARCHAR2(20 CHAR) DEFAULT 'USER' NOT NULL,
    EMAIL VARCHAR2(255 CHAR) NOT NULL,
    PASSWORD VARCHAR2(255 CHAR) NOT NULL,
    NICKNAME VARCHAR2(50 CHAR) NOT NULL,
    PHONE_NUMBER VARCHAR2(20 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE REGIONS (
    REGION_ID NUMBER NOT NULL,
    SIDO VARCHAR2(30 CHAR) NOT NULL,
    SIGUNGU VARCHAR2(50 CHAR) NOT NULL,
    DISPLAY_NAME VARCHAR2(100 CHAR) NOT NULL,
    LATITUDE NUMBER(10, 7),
    LONGITUDE NUMBER(10, 7),
    AVG_RENT NUMBER(10, 0),
    AVG_MANAGEMENT_FEE NUMBER(10, 0),
    TRANSPORT_SCORE NUMBER(3, 0),
    INFRA_SCORE NUMBER(3, 0),
    SAFETY_SCORE NUMBER(3, 0),
    SUPPORT_SCORE NUMBER(3, 0),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REGIONS PRIMARY KEY (REGION_ID),
    CONSTRAINT UK_REGIONS_DISPLAY_NAME UNIQUE (DISPLAY_NAME)
);

CREATE TABLE HOUSING_CONDITIONS (
    CONDITION_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    HOUSEHOLD_TYPE VARCHAR2(30 CHAR) NOT NULL,
    DESIRED_AREA VARCHAR2(100 CHAR) NOT NULL,
    WORK_LOCATION VARCHAR2(100 CHAR),
    DEPOSIT_BUDGET NUMBER(12, 0),
    MONTHLY_RENT_BUDGET NUMBER(10, 0) NOT NULL,
    MAX_COMMUTE_MINUTES NUMBER(4, 0),
    HOUSING_TYPE VARCHAR2(30 CHAR),
    PRIORITY_CONDITIONS VARCHAR2(500 CHAR),
    IS_ACTIVE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HOUSING_CONDITIONS PRIMARY KEY (CONDITION_ID),
    CONSTRAINT FK_HOUSING_CONDITIONS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT CK_HOUSING_CONDITIONS_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

CREATE TABLE RECOMMENDATIONS (
    RECOMMENDATION_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    CONDITION_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'COMPLETED' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RECOMMENDATIONS PRIMARY KEY (RECOMMENDATION_ID),
    CONSTRAINT FK_RECOMMENDATIONS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT FK_RECOMMENDATIONS_CONDITION FOREIGN KEY (CONDITION_ID) REFERENCES HOUSING_CONDITIONS (CONDITION_ID)
);

CREATE TABLE RECOMMENDATION_REGIONS (
    RECOMMENDATION_REGION_ID NUMBER NOT NULL,
    RECOMMENDATION_ID NUMBER NOT NULL,
    REGION_ID NUMBER NOT NULL,
    RANKING NUMBER(2, 0) NOT NULL,
    MATCH_SCORE NUMBER(3, 0) NOT NULL,
    ESTIMATED_RENT NUMBER(10, 0),
    ESTIMATED_COMMUTE_MINUTES NUMBER(4, 0),
    SUMMARY VARCHAR2(500 CHAR),
    CONSTRAINT PK_RECOMMENDATION_REGIONS PRIMARY KEY (RECOMMENDATION_REGION_ID),
    CONSTRAINT FK_RECOMMENDATION_REGIONS_RECOMMENDATION FOREIGN KEY (RECOMMENDATION_ID) REFERENCES RECOMMENDATIONS (RECOMMENDATION_ID),
    CONSTRAINT FK_RECOMMENDATION_REGIONS_REGION FOREIGN KEY (REGION_ID) REFERENCES REGIONS (REGION_ID),
    CONSTRAINT UK_RECOMMENDATION_REGIONS_RANK UNIQUE (RECOMMENDATION_ID, RANKING)
);

CREATE TABLE FAVORITES (
    FAVORITE_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    REGION_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FAVORITES PRIMARY KEY (FAVORITE_ID),
    CONSTRAINT FK_FAVORITES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT FK_FAVORITES_REGION FOREIGN KEY (REGION_ID) REFERENCES REGIONS (REGION_ID),
